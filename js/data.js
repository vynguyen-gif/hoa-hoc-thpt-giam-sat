function initChemStorage() {
    const CURRENT_ROSTER_TAG = "ROSTER_11A1_FRESH_EXAM_V5";
    localStorage.setItem("CHEM_TEACHER", JSON.stringify(CHEM_DATA.teacher));

    if (localStorage.getItem("CHEM_ROSTER_TAG") !== CURRENT_ROSTER_TAG) {
        localStorage.setItem("CHEM_STUDENTS", JSON.stringify(CHEM_DATA.initialStudents));
        localStorage.setItem("CHEM_ROSTER_TAG", CURRENT_ROSTER_TAG);
    }
}
